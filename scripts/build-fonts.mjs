/**
 * Generates `src/lib/export/fonts.generated.ts`: JetBrains Mono Regular and
 * Bold as base64, for pdfmake's virtual file system.
 *
 * The fonts are embedded in the bundle rather than fetched at export time, so
 * a generated PDF costs zero network requests (see NETWORK.md). Run with
 * `npm run fonts` after changing the font source; the output is committed.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as fontkit from 'fontkit';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'node_modules/@fontpkg/jet-brains-mono');
const out = resolve(root, 'src/lib/export/fonts.generated.ts');

const FACES = [
	{ key: 'normal', file: 'JetBrainsMono-Regular.ttf' },
	{ key: 'bold', file: 'JetBrainsMono-Bold.ttf' }
];

/**
 * Glyphs the PDF relies on (PRD §6.1). A missing glyph in a monospace font
 * renders as a blank box, which is worse than a substitution, so fail loudly.
 */
const REQUIRED = [
	['·', 'MIDDLE DOT (slot separator)'],
	['—', 'EM DASH (empty value)'],
	['→', 'RIGHTWARDS ARROW (date range)'],
	['×', 'MULTIPLICATION SIGN (scenario x model)'],
	['“', 'LEFT DOUBLE QUOTATION MARK'],
	['”', 'RIGHT DOUBLE QUOTATION MARK'],
	['‘', 'LEFT SINGLE QUOTATION MARK'],
	['’', 'RIGHT SINGLE QUOTATION MARK'],
	['…', 'HORIZONTAL ELLIPSIS']
];

/** Nice to have; substituted rather than fatal. */
const OPTIONAL = [['⚠', 'WARNING SIGN', '[!]']];

const substitutions = [];
let total = 0;
const faces = [];

for (const face of FACES) {
	const path = resolve(src, face.file);
	const bytes = readFileSync(path);
	total += bytes.length;

	const font = fontkit.openSync(path);
	for (const [glyph, name] of REQUIRED) {
		if (!font.hasGlyphForCodePoint(glyph.codePointAt(0))) {
			throw new Error(`${face.file} has no glyph for ${glyph} (${name}) — pick a glyph-complete font`);
		}
	}
	for (const [glyph, name, fallback] of OPTIONAL) {
		if (!font.hasGlyphForCodePoint(glyph.codePointAt(0))) {
			substitutions.push({ glyph, name, fallback, face: face.file });
		}
	}

	faces.push({ ...face, base64: bytes.toString('base64'), bytes: bytes.length });
	console.log(`  ${face.file}  ${(bytes.length / 1024).toFixed(0)} KB  glyphs ok`);
}

const unique = [...new Map(substitutions.map((s) => [s.glyph, s])).values()];

const lines = [
	'/* GENERATED by scripts/build-fonts.mjs — do not edit. Run `npm run fonts`. */',
	'/* eslint-disable */',
	'',
	"/** pdfmake virtual file system: face filename -> base64 TTF. */",
	'export const FONT_VFS: Record<string, string> = {'
];
for (const face of faces) {
	lines.push(`\t'${face.file}': '${face.base64}',`);
}
lines.push('};', '');
lines.push('/** Family used for every piece of body text in the report. */');
lines.push("export const PDF_FONT = 'JetBrainsMono';");
lines.push('');
lines.push('/**');
lines.push(' * Family used for text *inside* the chart SVGs, and only there.');
lines.push(' *');
lines.push(' * pdfmake 0.3 requires font sources to be strings (`Printer.resolveUrls`');
lines.push(' * rewrites every descriptor value as a URL), and svg-to-pdfkit hands that');
lines.push(" * string straight to pdfkit's own file loader — which, in the browser, knows");
lines.push(" * nothing about pdfmake's virtual filesystem. So an embedded TTF cannot back");
lines.push(' * SVG <text>: the labels would silently vanish from every chart.');
lines.push(' *');
lines.push(' * One of the 14 standard PDF fonts needs no file at all. Courier is');
lines.push(' * monospace with the same 0.6em advance as JetBrains Mono, so the chart');
lines.push(' * layout maths is unchanged and only small tick labels differ in shape.');
lines.push(' */');
lines.push("export const PDF_SVG_FONT = 'Courier';");
lines.push('');
lines.push('/** pdfmake font descriptor. Italics map to the upright faces: the report');
lines.push(' *  never sets italics, and it keeps the bundle two faces lighter. */');
lines.push('export const PDF_FONTS = {');
lines.push(`\t[PDF_FONT]: {`);
lines.push(`\t\tnormal: '${FACES[0].file}',`);
lines.push(`\t\tbold: '${FACES[1].file}',`);
lines.push(`\t\titalics: '${FACES[0].file}',`);
lines.push(`\t\tbolditalics: '${FACES[1].file}'`);
lines.push('\t},');
lines.push('\t[PDF_SVG_FONT]: {');
lines.push("\t\tnormal: 'Courier',");
lines.push("\t\tbold: 'Courier-Bold',");
lines.push("\t\titalics: 'Courier-Oblique',");
lines.push("\t\tbolditalics: 'Courier-BoldOblique'");
lines.push('\t}');
lines.push('};');
lines.push('');
lines.push('/** Glyphs this font lacks, with the text to substitute (PRD §6.1). */');
lines.push('export const GLYPH_SUBSTITUTIONS: Record<string, string> = {');
for (const sub of unique) {
	lines.push(`\t'${sub.glyph}': '${sub.fallback}', // ${sub.name}`);
}
lines.push('};');
lines.push('');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'), 'utf8');

console.log(`\nwrote ${out}`);
console.log(`  ${(total / 1024).toFixed(0)} KB of TTF -> ${(Buffer.byteLength(lines.join('\n')) / 1024).toFixed(0)} KB of base64`);
if (unique.length > 0) {
	console.log(`  substituting: ${unique.map((s) => `${s.glyph} -> ${s.fallback}`).join(', ')}`);
}
